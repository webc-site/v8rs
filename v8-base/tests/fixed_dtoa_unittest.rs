use std::str::from_utf8;

use aok::{OK, Void};
use v8_base::numbers::fixed_dtoa::fast_fixed_dtoa;

#[ctor::ctor(unsafe)]
fn _log_init() {
  log_init::init();
}

/// FastFixedDtoaTest.FastFixedVariousDoubles
#[test]
fn fast_fixed_various_doubles() -> Void {
  let mut buf = [0u8; 500];

  // (v, fractional_count, 期望串, 期望 point)
  let cases: &[(f64, i32, &str, i32)] = &[
    (1.0, 1, "1", 1),
    (1.0, 15, "1", 1),
    (1.0, 0, "1", 1),
    (4294967295.0, 5, "4294967295", 10),
    (4294967296.0, 5, "4294967296", 10),
    (1e21, 5, "1", 22),
    (999999999999999868928.00, 2, "999999999999999868928", 21),
    (
      f64::from_bits(0x4477_B788_3C06_9165), /* 6.9999999999999989514240000e21 */
      5,
      "6999999999999998951424",
      22,
    ),
    (1.5, 5, "15", 1),
    (1.55, 5, "155", 1),
    (1.55, 1, "16", 1),
    (1.00000001, 15, "100000001", 1),
    (0.1, 10, "1", 0),
    (0.01, 10, "1", -1),
    (0.001, 10, "1", -2),
    (0.0001, 10, "1", -3),
    (0.00001, 10, "1", -4),
    (0.000001, 10, "1", -5),
    (0.0000001, 10, "1", -6),
    (0.00000001, 10, "1", -7),
    (0.000000001, 10, "1", -8),
    (0.0000000001, 15, "1", -9),
    (0.00000000001, 15, "1", -10),
    (0.000000000001, 15, "1", -11),
    (0.0000000000001, 15, "1", -12),
    (0.00000000000001, 15, "1", -13),
    (0.000000000000001, 20, "1", -14),
    (0.0000000000000001, 20, "1", -15),
    (0.00000000000000001, 20, "1", -16),
    (0.000000000000000001, 20, "1", -17),
    (0.0000000000000000001, 20, "1", -18),
    (0.00000000000000000001, 20, "1", -19),
    // 尾部略小于 0.5ulp 的舍入边界: 全部舍去
    (0.10000000004, 10, "1", 0),
    (0.01000000004, 10, "1", -1),
    (0.00100000004, 10, "1", -2),
    (0.00010000004, 10, "1", -3),
    (0.00001000004, 10, "1", -4),
    (0.00000100004, 10, "1", -5),
    (0.00000010004, 10, "1", -6),
    (0.00000001004, 10, "1", -7),
    (0.00000000104, 10, "1", -8),
    (0.0000000001000004, 15, "1", -9),
    (0.0000000000100004, 15, "1", -10),
    (0.0000000000010004, 15, "1", -11),
    (0.0000000000001004, 15, "1", -12),
    (0.0000000000000104, 15, "1", -13),
    (0.000000000000001000004, 20, "1", -14),
    (0.000000000000000100004, 20, "1", -15),
    (0.000000000000000010004, 20, "1", -16),
    (0.000000000000000001004, 20, "1", -17),
    (0.000000000000000000104, 20, "1", -18),
    (0.000000000000000000014, 20, "1", -19),
    // 尾部略大于 0.5ulp: 进位
    (0.10000000006, 10, "1000000001", 0),
    (0.01000000006, 10, "100000001", -1),
    (0.00100000006, 10, "10000001", -2),
    (0.00010000006, 10, "1000001", -3),
    (0.00001000006, 10, "100001", -4),
    (0.00000100006, 10, "10001", -5),
    (0.00000010006, 10, "1001", -6),
    (0.00000001006, 10, "101", -7),
    (0.00000000106, 10, "11", -8),
    (0.0000000001000006, 15, "100001", -9),
    (0.0000000000100006, 15, "10001", -10),
    (0.0000000000010006, 15, "1001", -11),
    (0.0000000000001006, 15, "101", -12),
    (0.0000000000000106, 15, "11", -13),
    (0.000000000000001000006, 20, "100001", -14),
    (0.000000000000000100006, 20, "10001", -15),
    (0.000000000000000010006, 20, "1001", -16),
    (0.000000000000000001006, 20, "101", -17),
    (0.000000000000000000106, 20, "11", -18),
    (0.000000000000000000016, 20, "2", -19),
    // 0.999..9x 进位链: 升位
    (0.6, 0, "1", 1),
    (0.96, 1, "1", 1),
    (0.996, 2, "1", 1),
    (0.9996, 3, "1", 1),
    (0.99996, 4, "1", 1),
    (0.999996, 5, "1", 1),
    (0.9999996, 6, "1", 1),
    (0.99999996, 7, "1", 1),
    (0.999999996, 8, "1", 1),
    (0.9999999996, 9, "1", 1),
    (0.99999999996, 10, "1", 1),
    (0.999999999996, 11, "1", 1),
    (0.9999999999996, 12, "1", 1),
    (0.99999999999996, 13, "1", 1),
    (0.999999999999996, 14, "1", 1),
    (0.9999999999999996, 15, "1", 1),
    (0.00999999999999996, 16, "1", -1),
    (0.000999999999999996, 17, "1", -2),
    (0.0000999999999999996, 18, "1", -3),
    (0.00000999999999999996, 19, "1", -4),
    (0.000000999999999999996, 20, "1", -5),
    (323423.234234, 10, "323423234234", 6),
    (12345678.901234, 4, "123456789012", 8),
    (98765.432109, 5, "9876543211", 5),
    (42.0, 20, "42", 2),
    (0.5, 0, "1", 1),
    // 过小数: 空串 + point = -fractional_count
    (1e-23, 10, "", -10),
    (1e-123, 2, "", -2),
    (1e-123, 0, "", 0),
    (1e-23, 20, "", -20),
    (1e-21, 20, "", -20),
    (1e-22, 20, "", -20),
    (6e-21, 20, "1", -19),
    (
      f64::from_bits(0x4413_C643_3B72_9255), /* 9.1193616301674545152000000e19 */
      0,
      "91193616301674545152",
      20,
    ),
    (
      f64::from_bits(0x3F3F_940B_7A9F_DFA0), /* 4.8184662102767651659096515e-04 */
      19,
      "4818466210276765",
      -3,
    ),
    (
      f64::from_bits(0x3B36_FF62_58DC_6FA0), /* 1.9023164229540652612705182e-23 */
      8,
      "",
      -8,
    ),
    (1000000000000000128.0, 0, "1000000000000000128", 19),
  ];

  for &(v, count, want, want_point) in cases {
    let r = fast_fixed_dtoa(v, count, &mut buf)
      .unwrap_or_else(|| panic!("FastFixedDtoa({v:e}, {count}) 失败"));
    let got = from_utf8(&buf[..r.length]).unwrap_or("?");
    assert_eq!(got, want, "v={v:e} count={count}");
    assert_eq!(r.decimal_point, want_point, "point: v={v:e} count={count}");
  }
  OK
}
