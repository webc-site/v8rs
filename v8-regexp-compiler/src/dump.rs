//! 字节码反汇编文本面 (v8/src/regexp/regexp-bytecodes.cc:19-98 的可静态验证部分)。
//!
//! 原版 RegExpBytecodeDisassembleSingle 经 std::ostream + AsHex/AsUC32 输出;
//! 本文件以纯函数复刻其逐字符格式 (金标准: ostreams.cc 的 AsHex/PrintUC16 语义):
//! - AsHex(v, 2): 小写十六进制, 最小 2 位, 无前缀; 有符号操作数按 uint64 形参
//!   符号扩展后取位模式 (ostreams.cc AsHex 的 uint64_t 隐式转换)
//! - AsUC32(char): 可打印 ASCII (0x20..=0x7E) 直写; ≤0xFF → \x%02x; 其余 → \u%04x
//! - 枚举: StackCheckFlag → NoCheck/Check, StandardCharacterSet → 九名表
//!   (cc:21-52); 位模式域外 = 原版 UNREACHABLE → UnknownEnumEncoding
//! - BitTable: 16 字节 × AsHex(byte, 2) 无分隔拼接
//!
//! 推迟登记: RegExpBytecodeDisassemble 的 `%p` 指针列非确定性 (运行期地址),
//! 本落地行首仅保留 `%4x  ` 偏移列; StdoutStream/print 副作用改返回 String。

use crate::{
  bytecodes::{Operand, opcode_at},
  bytecodes_generated::Bytecode,
  error::{Error, Result},
};

/// 原版 regexp-bytecodes.cc:30-52 StandardCharacterSet 的 operator<< 名表
/// (switch 序 = kWhitespace..kWord 声明序; 键为 char 位模式)
pub const STANDARD_CHARACTER_SET_NAMES: [(u8, &str); 9] = [
  (b's', "Whitespace"),
  (b'S', "NotWhitespace"),
  (b'd', "Digit"),
  (b'D', "NotDigit"),
  (b'n', "LineTerminator"),
  (b'.', "NotLineTerminator"),
  (b'w', "Word"),
  (b'W', "NotWord"),
  (b'*', "Everything"),
];

/// 原版 AsHex(v, 2) (ostreams.cc: snprintf "%.*" PRIx64, 小写, 最小 2 位)
pub fn as_hex(value: u64) -> String {
  let s = format!("{value:x}");
  if s.len() < 2 { format!("{s:0>2}") } else { s }
}

/// 原版 AsUC32/PrintUC16 (ostreams.cc:127-133/143-151, IsPrint = 0x20..=0x7E)
fn as_uc16(c: u16) -> String {
  if (0x20..=0x7E).contains(&c) {
    format!("{}", char::from(c as u8))
  } else if c <= 0xFF {
    format!("\\x{c:02x}")
  } else {
    format!("\\u{c:04x}")
  }
}

fn standard_character_set_name(byte: u8) -> Result<&'static str> {
  STANDARD_CHARACTER_SET_NAMES
    .iter()
    .find(|(c, _)| *c == byte)
    .map(|(_, n)| *n)
    .ok_or(Error::UnknownEnumEncoding {
      kind: "StandardCharacterSet",
      value: byte,
    })
}

pub fn stack_check_flag_name(byte: u8) -> Result<&'static str> {
  // 原版 enum : uint8_t { kNoStackLimitCheck = false, kCheckStackLimit = true }
  match byte {
    0 => Ok("NoCheck"),
    1 => Ok("Check"),
    v => Err(Error::UnknownEnumEncoding {
      kind: "StackCheckFlag",
      value: v,
    }),
  }
}

/// 单操作数的 Dump 文本 (regexp-bytecodes.cc:63-80 ForEachOperand 分支)
fn format_operand(operand: &Operand<'_>) -> Result<String> {
  Ok(match operand {
    Operand::BitTable(table) => {
      // 原版逐字节 AsHex(val[i], 2) 连续拼接 (cc:69-72)
      let mut s = String::with_capacity(32);
      for b in table.iter().take(16) {
        s.push_str(&as_hex(u64::from(*b)));
      }
      s
    }
    Operand::Char(c) => as_uc16(*c),
    Operand::StackCheckFlag(v) => stack_check_flag_name(*v)?.to_string(),
    Operand::StandardCharacterSet(v) => standard_character_set_name(*v)?.to_string(),
    // 其余整型: AsHex(val, 2), 有符号按 uint64 符号扩展取位模式
    Operand::Int16(v) => as_hex(*v as i64 as u64),
    Operand::Offset(v) => as_hex(*v as i64 as u64),
    Operand::Int32(v) | Operand::BoundsCheckOffset(v) => as_hex(*v as i64 as u64),
    Operand::Uint32(v) | Operand::JumpTarget(v) => as_hex(u64::from(*v)),
    Operand::Register(v) => as_hex(u64::from(*v)),
  })
}

/// 原版 RegExpBytecodeDisassembleSingle (cc:56-83) 的纯函数形态:
/// 返回 "Name, op0: v0, op1: v1\n"; pc 越界/非法 opcode → Err
pub fn disassemble_single(code: &[u8], pc: usize) -> Result<String> {
  let bc = opcode_at(code, pc).ok_or(Error::InvalidBytecode {
    byte: *code.get(pc).unwrap_or(&u8::MAX),
  })?;
  let mut os = String::from(bc.name());
  for i in 0..bc.operand_count() {
    let value = bc.read_operand(code, pc, i).ok_or(Error::Truncated {
      offset: pc,
      need: pc + bc.operand_offset(i) + bc.operand_size(i),
      have: code.len(),
    })?;
    os.push_str(", ");
    os.push_str(bc.operand_name(i));
    os.push_str(": ");
    os.push_str(&format_operand(&value)?);
  }
  os.push('\n');
  Ok(os)
}

/// 原版 RegExpBytecodeDisassemble (cc:85-98): 头部提示行 + 逐条
/// `%4x  <单条>` (指针列推迟登记, 见模块头)。offset 推进 ≡ cc:96
/// `offset += Bytecodes::Size(FromPtr(pc))`
pub fn disassemble(code: &[u8], length: usize, pattern: &str) -> Result<String> {
  let mut os = format!("[generated bytecode for regexp pattern: '{pattern}']\n");
  let mut offset = 0usize;
  while offset < length {
    let bc = opcode_at(code, offset).ok_or(Error::InvalidBytecode {
      byte: *code.get(offset).unwrap_or(&u8::MAX),
    })?;
    let size = usize::from(bc.size());
    if offset + size > length.min(code.len()) {
      return Err(Error::Truncated {
        offset,
        need: offset + size,
        have: length.min(code.len()),
      });
    }
    os.push_str(&format!("{offset:4x}  "));
    os.push_str(&disassemble_single(code, offset)?);
    offset += size;
  }
  Ok(os)
}

/// 布局行走 (静态验证面): 从 0 起按 Size 推进恰好在 length 处收尾则 Ok(指令数);
/// 非法 opcode / 越界 / 不能整除收尾 → Err — RegExpBytecodeDisassemble 循环
/// 不变式的可断言形态
pub fn walk(code: &[u8], length: usize) -> Result<usize> {
  let mut offset = 0usize;
  let mut count = 0usize;
  while offset < length {
    let bc = opcode_at(code, offset).ok_or(Error::InvalidBytecode {
      byte: *code.get(offset).unwrap_or(&u8::MAX),
    })?;
    let size = usize::from(bc.size());
    if offset + size > length {
      return Err(Error::Truncated {
        offset,
        need: offset + size,
        have: length,
      });
    }
    offset += size;
    count += 1;
  }
  if offset != length {
    return Err(Error::Truncated {
      offset,
      need: length,
      have: offset,
    });
  }
  Ok(count)
}

/// 组装单条指令到缓冲区尾部 (字节编码工具面: opcode 字节 + 块对齐操作数排布)
#[must_use]
pub fn encode(bytecode: Bytecode, operands: &[Operand<'_>]) -> Option<Vec<u8>> {
  if operands.len() != bytecode.operand_count() {
    return None;
  }
  let mut buf = vec![0u8; usize::from(bytecode.size())];
  buf[0] = bytecode.to_byte();
  for (i, op) in operands.iter().enumerate() {
    if !op.write(&mut buf, bytecode.operand_offset(i)) {
      return None;
    }
  }
  Some(buf)
}
