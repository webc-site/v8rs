/// cp_offset >= 0: cp_offset + characters - 1; 负: 原值
#[must_use]
pub const fn calculate_bounds_check_offset(cp_offset: i32, characters: i32) -> i32 {
  if cp_offset >= 0 {
    cp_offset + characters - 1
  } else {
    cp_offset
  }
}

