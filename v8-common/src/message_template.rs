/// 原版 MessageTemplateFromInt(message_id) (message-template.h:796) —
/// DCHECK 越界为进程终止, Rust 安全化返回 Option (登记)
pub fn message_template_from_int(id: i32) -> Option<MessageTemplate> {
  if id < 0 || id >= K_MESSAGE_COUNT as i32 {
    return None;
  }
  MessageTemplate::from_repr(id as u16)
}

/// 模板串查找 — TypedArrayValidateWriteErrorOperation 依配置选分支串,
/// 其余按下标直取 (原版 MESSAGE_TEMPLATES 由 % 填充)
pub fn template_string(t: MessageTemplate) -> &'static str {
  if JS_IMMUTABLE_ARRAYBUFFER && t == MessageTemplate::TypedArrayValidateWriteErrorOperation {
    return TYPED_ARRAY_VALIDATE_WRITE_IMMUTABLE;
  }
  MESSAGE_TEMPLATE_STRINGS[t as usize]
}

impl fmt::Display for MessageTemplate {
  fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    f.write_str(template_string(*self))
  }
}
