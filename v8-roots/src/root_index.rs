impl RootIndex {
  /// 总根对象槽位数 (kRootListLength / kEntriesCount)
  pub const K_ENTRIES_COUNT: usize = 1157;

  /// 只读根对象总数 (kReadOnlyRootsCount)
  pub const K_READ_ONLY_ROOTS_COUNT: usize = 1044;

  /// 不可移动根对象总数 (含只读根与可变不可移动根)
  pub const K_IMMORTAL_IMMOVABLE_ROOTS_COUNT: usize = 1123;

  /// 可变强根对象总数 (kMutableRootsCount)
  pub const K_MUTABLE_ROOTS_COUNT: usize = 105;

  /// Smi 标记根对象总数 (SMI_ROOT_LIST)
  pub const K_SMI_ROOTS_COUNT: usize = 8;

  /// 单字符内部化字符串根数
  pub const K_SINGLE_CHARACTER_STRING_ROOTS_COUNT: usize = 256;

  /// 用于 Protector 快速检查的标识符名称根数
  pub const K_NAME_FOR_PROTECTOR_COUNT: usize = 12;

  /// 受信任对象 Map 根数
  pub const K_TRUSTED_OBJECT_MAP_ROOTS_COUNT: usize = 27;

  /// 可序列化受信任对象 Map 根数
  pub const K_SERIALIZABLE_TRUSTED_OBJECT_MAP_ROOTS_COUNT: usize = 7;

  // ── 区域首尾索引常量 ──
  pub const K_FIRST_ROOT: Self = Self::UndefinedValue;
  pub const K_LAST_ROOT: Self = Self::InterpreterEntryReturnPCOffset;

  pub const K_FIRST_READ_ONLY_ROOT: Self = Self::UndefinedValue;
  pub const K_LAST_READ_ONLY_ROOT: Self = Self::CppGCManagedBaseMap;

  pub const K_FIRST_STRONG_ROOT: Self = Self::ArgumentsIteratorAccessor;
  pub const K_LAST_STRONG_ROOT: Self = Self::ErrorStackSetterSharedFun;

  pub const K_FIRST_STRONG_OR_READ_ONLY_ROOT: Self = Self::UndefinedValue;
  pub const K_LAST_STRONG_OR_READ_ONLY_ROOT: Self = Self::ErrorStackSetterSharedFun;

  pub const K_FIRST_IMMORTAL_IMMOVABLE_ROOT: Self = Self::UndefinedValue;
  pub const K_LAST_IMMORTAL_IMMOVABLE_ROOT: Self = Self::EmptyWasmDispatchTable;

  pub const K_FIRST_SMI_ROOT: Self = Self::LastScriptId;
  pub const K_LAST_SMI_ROOT: Self = Self::InterpreterEntryReturnPCOffset;

  pub const K_FIRST_SINGLE_CHARACTER_STRING: Self = Self::AsciiNulString;
  pub const K_LAST_SINGLE_CHARACTER_STRING: Self = Self::Latin1FfString;

  pub const K_FIRST_NAME_FOR_PROTECTOR: Self = Self::ConstructorString;
  pub const K_LAST_NAME_FOR_PROTECTOR: Self = Self::IsConcatSpreadableSymbol;

  pub const K_FIRST_TRUSTED_OBJECT_MAP: Self = Self::AtomRegExpDataMap;
  pub const K_LAST_TRUSTED_OBJECT_MAP: Self = Self::UncompiledDataWithPreparseDataAndJobMap;

  pub const K_FIRST_SERIALIZABLE_TRUSTED_OBJECT_MAP: Self = Self::BytecodeArrayMap;
  pub const K_LAST_SERIALIZABLE_TRUSTED_OBJECT_MAP: Self =
    Self::UncompiledDataWithPreparseDataAndJobMap;

  pub const K_FIRST_BUILTIN_WITH_SFI_ROOT: Self = Self::ProxyRevokeSharedFun;
  pub const K_LAST_BUILTIN_WITH_SFI_ROOT: Self =
    Self::AsyncIteratorPrototypeAsyncDisposeResolveClosureSharedFun;
  pub const K_BUILTINS_WITH_SFI_ROOTS_COUNT: usize = 28;

  pub const K_FIRST_HEAP_NUMBER_ROOT: Self = Self::NanValue;
  pub const K_LAST_HEAP_NUMBER_ROOT: Self = Self::SmiMaxValuePlusOne;

  pub const K_FIRST_JS_RECEIVER_MAP_ROOT: Self = Self::JSSharedArrayMap;

  /// TDZ Hole 别名 (若未启用独立 TDZ Hole 则映射至 TheHoleValue)
  pub const K_TDZ_HOLE_VALUE: Self = Self::TheHoleValue;

  /// 从原始 u16 整数构造 RootIndex
  #[inline]
  pub const fn from_u16(val: u16) -> Option<Self> {
    if (val as usize) < Self::K_ENTRIES_COUNT {
      // SAFETY: 枚举定义包含 0..1157 连续所有变体，val < K_ENTRIES_COUNT 保证有效
      Some(unsafe { transmute::<u16, Self>(val) })
    } else {
      None
    }
  }

  /// 从原始 usize 整数构造 RootIndex
  #[inline]
  pub const fn from_usize(val: usize) -> Option<Self> {
    if val < Self::K_ENTRIES_COUNT {
      // SAFETY: 枚举定义包含 0..1157 连续所有变体
      Some(unsafe { transmute::<u16, Self>(val as u16) })
    } else {
      None
    }
  }

  /// 转换为 u16 整数值
  #[inline]
  pub const fn as_u16(self) -> u16 {
    self as u16
  }

  /// 转换为 usize 索引值
  #[inline]
  pub const fn as_usize(self) -> usize {
    self as usize
  }

  /// 判断当前根是否位于只读区
  #[inline]
  pub const fn is_read_only(self) -> bool {
    (self as usize) <= Self::K_LAST_READ_ONLY_ROOT as usize
  }

  /// 判断当前根是否为不可移动根 (Immortal Immovable)
  #[inline]
  pub const fn is_immortal_immovable(self) -> bool {
    (self as usize) <= Self::K_LAST_IMMORTAL_IMMOVABLE_ROOT as usize
  }

  /// 判断当前根是否属于受信任对象 Map 列表
  #[inline]
  pub const fn is_in_trusted_object_map_list(self) -> bool {
    let val = self as usize;
    val >= Self::K_FIRST_TRUSTED_OBJECT_MAP as usize
      && val <= Self::K_LAST_TRUSTED_OBJECT_MAP as usize
  }

  /// 判断当前根是否属于可序列化受信任对象 Map 列表
  #[inline]
  pub const fn is_in_serializable_trusted_object_map_list(self) -> bool {
    let val = self as usize;
    val >= Self::K_FIRST_SERIALIZABLE_TRUSTED_OBJECT_MAP as usize
      && val <= Self::K_LAST_SERIALIZABLE_TRUSTED_OBJECT_MAP as usize
  }

  /// 判断当前根是否为堆数字常量 (HeapNumber)
  #[inline]
  pub const fn is_heap_number(self) -> bool {
    let val = self as usize;
    val >= Self::K_FIRST_HEAP_NUMBER_ROOT as usize && val <= Self::K_LAST_HEAP_NUMBER_ROOT as usize
  }

  /// 判断当前根是否为可变强根 (Strong Mutable Root)
  #[inline]
  pub const fn is_strong(self) -> bool {
    let val = self as usize;
    val >= Self::K_FIRST_STRONG_ROOT as usize && val <= Self::K_LAST_STRONG_ROOT as usize
  }

  /// 判断当前根是否为 Smi 标记根
  #[inline]
  pub const fn is_smi(self) -> bool {
    let val = self as usize;
    val >= Self::K_FIRST_SMI_ROOT as usize && val <= Self::K_LAST_SMI_ROOT as usize
  }

  /// 根据单字节字符 code (0..=255) 计算其在根表中的 RootIndex
  #[inline]
  pub const fn single_character_string_index(c: u8) -> Self {
    let idx = Self::K_FIRST_SINGLE_CHARACTER_STRING as u16 + c as u16;
    // SAFETY: K_FIRST_SINGLE_CHARACTER_STRING=354, 354 + 255 = 609 = K_LAST_SINGLE_CHARACTER_STRING, 恒在范围内
    unsafe { transmute::<u16, Self>(idx) }
  }

  /// 获取根名称字符串字面量
  #[inline]
  pub const fn name(self) -> &'static str {
    ROOT_NAMES[self as usize]
  }
}

impl TryFrom<usize> for RootIndex {
  type Error = Error;

  #[inline]
  fn try_from(val: usize) -> Result<Self> {
    Self::from_usize(val).ok_or(Error::InvalidRootIndex(val))
  }
}

impl TryFrom<u16> for RootIndex {
  type Error = Error;

  #[inline]
  fn try_from(val: u16) -> Result<Self> {
    Self::from_u16(val).ok_or(Error::InvalidRootIndex(val as usize))
  }
}

impl From<RootIndex> for usize {
  #[inline]
  fn from(idx: RootIndex) -> Self {
    idx as usize
  }
}

impl From<RootIndex> for u16 {
  #[inline]
  fn from(idx: RootIndex) -> Self {
    idx as u16
  }
}

