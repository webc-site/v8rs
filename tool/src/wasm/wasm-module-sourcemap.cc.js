#!/usr/bin/env bun
// tool/src/wasm/wasm-module-sourcemap.cc.js
// 机械提取 v8/src/wasm/wasm-module-sourcemap.cc 的 sourcemap 版本门控、
// VLQ 解码字段表与查找语义。头侧骨架在 v8-wasm-core/src/wasm_module_sourcemap.rs.skel。

import { readV8, writeSrc, banner } from "../../lib.js";

const src = readV8("src/wasm/wasm-module-sourcemap.cc");

// ---------- 1. 版本门控: 仅 version == 3 ----------
if (!/version != 3u\)/.test(src)) throw new Error("版本门控 3 缺失");

// ---------- 2. 必需字段: sources 数组 + mappings 字符串 ----------
if (!src.includes('v8::String::NewFromUtf8Literal(v8_isolate, "sources")')) {
  throw new Error("sources 字段缺失");
}
if (!src.includes('v8::String::NewFromUtf8Literal(v8_isolate, "mappings")')) {
  throw new Error("mappings 字段缺失");
}
if (!src.includes("sources_value) &&\n      sources_value->IsArray();")) {
  throw new Error("sources 数组校验缺失");
}
if (!src.includes("mappings_value) &&\n      mappings_value->IsString();")) {
  throw new Error("mappings 字符串校验缺失");
}

// ---------- 3. VLQ 解码: 4 字段累加增量, 第 4 列解码后弃用 ----------
const vlqReads = [...src.matchAll(/gen_col \+= qnt;|file_idx \+= qnt;|ori_line \+= qnt;/g)];
if (vlqReads.length !== 3) throw new Error(`VLQ 累加字段 ${vlqReads.length} != 3`);
if (!src.includes("// Column number in source file is always 0 in source map generated by")) {
  throw new Error("第 4 列弃用语义缺失");
}

// ---------- 4. 解码失败哨兵: int32 最小值 ----------
if (!src.includes("std::numeric_limits<int32_t>::min()")) {
  throw new Error("VLQ 失败哨兵缺失");
}

// ---------- 5. 分隔符规则: 逗号跳过, 4 字段后必须逗号或结尾 ----------
if (!src.includes("if (s[pos] == ',') {\n      ++pos;\n      continue;\n    }")) {
  throw new Error("逗号跳过缺失");
}
if (!src.includes("if (pos < s.size() && s[pos] != ',') return false;")) {
  throw new Error("字段终止校验缺失");
}

// ---------- 6. 查找语义: upper_bound 二分, 命中前驱条目 ----------
if (!src.includes("std::upper_bound(offsets.begin(), offsets.end(), wasm_offset)")) {
  throw new Error("GetSourceLine 二分缺失");
}
if (!src.includes("if (up == offsets.begin()) return false;")) {
  throw new Error("HasValidEntry 前驱缺失缺失");
}

// ---------- 7. HasSource 半开区间 ----------
if (!src.includes("return start <= *(offsets.end() - 1) && end > *offsets.begin();")) {
  throw new Error("HasSource 区间判定缺失");
}

// ---------- 8. 大小估算基准 ----------
const est = src.match(/UPDATE_WHEN_CLASS_CHANGES\(WasmModuleSourceMap, (\d+)\)/);
if (!est || est[1] !== "104") throw new Error("sizeof 基准 != 104");

console.log("wasm-module-sourcemap: 版本=3 VLQ字段=4(3累加+1弃用) sizeof=104");

// ---------- 生成 Rust ----------
const rust = `${banner(
  "src/wasm/wasm-module-sourcemap.cc.js",
  "src/wasm/wasm-module-sourcemap.cc",
  "sourcemap 版本门控与 VLQ 映射解码语义",
)}
//! Wasm 模块 sourcemap (version 3)。

/// 支持的 sourcemap 版本 (其余版本整体视为无效)
/// v8: src/wasm/wasm-module-sourcemap.cc WasmModuleSourceMap 构造
pub const SUPPORTED_VERSION: u32 = 3;

/// 必需字段: "sources" 必须为数组, "mappings" 必须为字符串
/// v8: src/wasm/wasm-module-sourcemap.cc WasmModuleSourceMap 构造
#[rustfmt::skip]
pub static REQUIRED_FIELDS: &[(&str, &str)] = &[
    ("sources", "IsArray"),
    ("mappings", "IsString"),
];

/// VLQ 解码字段: 前 3 个为相对增量累加, 第 4 个 (源列号) 解码后弃用
/// v8: src/wasm/wasm-module-sourcemap.cc DecodeMapping
#[rustfmt::skip]
pub static VLQ_FIELDS: &[(&str, bool)] = &[
    ("gen_col (生成列)", true),
    ("file_idx (文件索引)", true),
    ("ori_line (源行)", true),
    ("源列号 (Emscripten 恒 0)", false),
];

/// VLQ 解码失败哨兵 (int32 最小值, 绝不会是合法增量)
/// v8: src/wasm/wasm-module-sourcemap.cc DecodeMapping
pub const VLQ_ERROR_SENTINEL: i32 = i32::MIN;

/// 分隔规则: 冗余逗号跳过; 每组 4 字段后必须是逗号或串尾
/// v8: src/wasm/wasm-module-sourcemap.cc DecodeMapping
pub const SEPARATOR_RULE: &str = "',' 跳过; 4 字段后须 ',' 或结尾";

/// 行号/文件名查找: offsets 上 upper_bound, 取命中位置的前驱条目
/// v8: src/wasm/wasm-module-sourcemap.cc GetSourceLine / GetFilename
pub const LOOKUP_SEMANTICS: &str = "upper_bound 前驱";
/// HasValidEntry: 无前驱 (addr 在首条前) 返回 false; 命中条目的 offset 须 >= start
/// v8: src/wasm/wasm-module-sourcemap.cc HasValidEntry
pub const HAS_VALID_ENTRY_SEMANTICS: &str = "前驱存在且 entry_offset >= start";

/// HasSource 半开区间: start <= 最大 offset 且 end > 最小 offset
/// v8: src/wasm/wasm-module-sourcemap.cc HasSource
pub const HAS_SOURCE_SEMANTICS: &str = "start <= last && end > first";

/// sizeof(WasmModuleSourceMap) 估算基准
/// v8: src/wasm/wasm-module-sourcemap.cc EstimateCurrentMemoryConsumption
pub const SIZEOF_WASM_MODULE_SOURCE_MAP: usize = ${est[1]};

// —— 提取不变式断言 ——
const _: () = {
    assert_eq!(SUPPORTED_VERSION, 3);
    assert_eq!(REQUIRED_FIELDS.len(), 2);
    assert_eq!(VLQ_FIELDS.len(), 4);
    assert_eq!(VLQ_FIELDS.iter().filter(|f| f.1).count(), 3);
    assert_eq!(VLQ_ERROR_SENTINEL, -2147483648);
    assert_eq!(SIZEOF_WASM_MODULE_SOURCE_MAP, 104);
};
`;

const p = writeSrc("v8-wasm-objects", "wasm_module_sourcemap_cc.rs", rust);
console.log(`written ${p}`);
