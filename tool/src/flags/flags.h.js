// 提取规则:
//   - FlagValue<T> static_assert 允许类型类别 (算术 / optional<bool> / const char*) → 8 具体类型表核对
//   - enum class FlagProcessingMode 变体 (kXxx → Xxx) + 逐变体注释
//   - FlagList::FreezeFlags/IsFrozen → Flags.frozen 字段语义
//   - FlagValue<T>::operator= 的 ResetFlagHash 语义 → 变更走统一 assign 路径 (frozen 拒写)
