// ---- 提取 1: static_assert 允许类型类别 (防 v8 上游改动漂移) ----
const allow = src.match(/static_assert\(std::is_arithmetic_v<T>\s*\|\|\s*std::is_same_v<std::optional<bool>, T>\s*\|\|\s*std::is_same_v<const char\*, T>\);/);
if (!allow) throw new Error("flags.h FlagValue static_assert 允许类型类别已变, 需人工核对脚本");

// ---- 提取 2: FlagProcessingMode 变体 + 前置注释 ----
const modeEnum = src.match(/enum class FlagProcessingMode \{([\s\S]*?)\n\};/);
if (!modeEnum) throw new Error("flags.h FlagProcessingMode 枚举未找到");
const modeVariants = [];
{
  const lines = modeEnum[1].split("\n");
  let doc = "";
  for (const ln of lines) {
    const c = ln.match(/^\s*\/\/\s?(.*)$/);
    if (c) { doc += (doc ? " " : "") + c[1].trim(); continue; }
    const v = ln.match(/^\s*k([A-Za-z]+),?\s*$/);
    if (v) { modeVariants.push({ name: v[1], doc }); doc = ""; }
  }
  if (modeVariants.length !== 3) throw new Error(`FlagProcessingMode 变体数异常: ${modeVariants.length}`);
}

