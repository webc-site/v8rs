#!/usr/bin/env bun
// test/unittests/gay-{shortest,fixed,precision}.cc → v8-numbers/tests/data/*.tsv
// Gay 黄金数据: 每行  bits(hex) TAB extra TAB digits TAB point
//   shortest: extra 无 (恒 0); fixed: extra=fractional_count; precision: extra=precision
// double 字面量经 IEEE754 位型 (Float64Array→BigUint64Array) 无损落盘,
// Rust 侧 f64::from_bits(u64::from_str_radix) 重建, 避免十进制再解析
// 对数断言: 解析条数 == 数组内 entry 计数 == 写出行数
import { readV8 } from "../../lib.js";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { root } from "../../lib.js";

const f64 = new Float64Array(1);
const u64 = new BigUint64Array(f64.buffer);

function bitsOf(literal) {
  f64[0] = Number(literal);
  return u64[0].toString(16);
}

// 条目: shortest {<double>, "<digits>", <point>}; fixed/precision {<double>, <int>, "<digits>", <point>}
const RE4 = /\{\s*(-?[\d.]+(?:[eE][+-]?\d+)?)\s*,\s*(-?\d+)\s*,\s*"([^"]*)"\s*,\s*(-?\d+)\s*,?\s*\}/g;
const RE3 = /\{\s*(-?[\d.]+(?:[eE][+-]?\d+)?)\s*,\s*"([^"]*)"\s*,\s*(-?\d+)\s*,?\s*\}/g;

function extract(file, extraName, re) {
  const src = readV8(`test/unittests/${file}.cc`);
  const rows = [];
  let m;
  while ((m = re.exec(src))) {
    if (re === RE3) {
      const [, vLit, digits, point] = m;
      rows.push([bitsOf(vLit), "0", digits, point].join("\t"));
    } else {
      const [, vLit, extra, digits, point] = m;
      rows.push([bitsOf(vLit), extra, digits, point].join("\t"));
    }
  }
  // 对数: entry 总数应与 "  {" 行计数一致 (每行一条, 10 万级)
  const braceCount = (src.match(/^\s*\{/gm) ?? []).length;
  if (rows.length !== braceCount) {
    throw new Error(`${file}: 条数 ${rows.length} != 花括号行 ${braceCount}`);
  }
  if (rows.length < 1000) throw new Error(`${file}: 条数异常 ${rows.length}`);
  const out = join(root, "v8-numbers/tests/data", `${file}.tsv`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `# v\t${extraName}\tdigits\tpoint (generated by tool/src/numbers/gay-data.js)\n` + rows.join("\n") + "\n");
  console.log(`${file}: ${rows.length} rows -> ${out}`);
}

extract("gay-shortest", "-", RE3);
extract("gay-fixed", "fractional_count", RE4);
extract("gay-precision", "precision", RE4);
