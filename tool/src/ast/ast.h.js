// 生成类别桥接枚举 (Statement/Expression/Declaration): 变体按对应 X-macro 子表顺序
function bridgeEnum(rustName, doc, variants) {
  return [
    `/// ${doc}, ${variants.length} 种`,
    `#[derive(Debug, Clone, PartialEq)]`,
    `pub enum ${rustName} {`,
    ...variants.map((v) => `  ${v}(${v}),`),
    `}`,
    ``,
    `impl ${rustName} {`,
    `  /// 种类数 (与原版 X-macro 展开 1:1)`,
    `  pub const COUNT: usize = ${variants.length};`,
    ``,
    `  /// 节点类型枚举 (与 AstNodeType 对齐)`,
    `  pub const fn node_type(&self) -> AstNodeType {`,
    `    match self {`,
    ...variants.map((v) => `      Self::${v}(_) => AstNodeType::${v},`),
    `    }`,
    `  }`,
    ``,
    `  /// 提升回通用节点 (原版向上转型到 AstNode)`,
    `  pub fn into_node(self) -> AstNode {`,
    `    match self {`,
    ...variants.map((v) => `      Self::${v}(n) => AstNode::${v}(n),`),
    `    }`,
    `  }`,
    ``,
    `  /// 从通用节点静态转换 (原版 As##type 向下转型, 类型不符返回 None)`,
    `  pub fn from_node(node: AstNode) -> Option<Self> {`,
    `    match node {`,
    ...variants.map((v) => `      AstNode::${v}(n) => Some(Self::${v}(n)),`),
    `      _ => None,`,
    `    }`,
    `  }`,
    `}`,
    ``,
  ];
}

