// 1. 提取各个 NODE_LIST 宏
function extractMacroList(src, macroName) {
  const re = new RegExp(`#define\\s+${macroName}\\(V\\)([\\s\\S]*?)(?=\\n#define|\\n\\nclass|\\n\\/\\/\\s*-|\\n\\/\\*|$)`);
  const m = src.match(re);
  if (!m) throw new Error(`未找到宏 ${macroName}`);
  const body = m[1];
  const items = [];
  const itemRe = /V\((\w+)\)/g;
  let match;
  while ((match = itemRe.exec(body)) !== null) {
    items.push(match[1]);
  }
  return items;
}

