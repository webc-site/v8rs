#!/usr/bin/env bun
// tool/src/regexp/regexp-bytecodes.cc.js — v8/src/regexp/regexp-bytecodes.{cc,-inl.h}
//   → v8-regexp-exec/src/bytecodes_cc_generated.rs
// 机械提取: cc 侧 StackCheckFlag/StandardCharacterSet 运算符名表 + 反汇编
//   头/行格式 + 操作数值格式规则; inl.h 侧 61 条 opcode 布局金标准
//   (GOLDEN_OFFSETS 逐条操作数偏移, JS 独立复刻 CalculateAlignedOffsets) +
//   detail 四表结构断言 + DispatchOnBytecode 61 case;
// 对数断言: 名表 2/9 (与 macro-assembler.h/regexp-ast.h 交叉), opcode 61,
//   偏移数组总数; 与 v8-regexp-compiler/src/bytecodes_generated.rs 双向交叉。
import { banner, readV8, writeSrc, root } from "../../lib.js";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const cc = readV8("src/regexp/regexp-bytecodes.cc");
const inl = readV8("src/regexp/regexp-bytecodes-inl.h");
const bcH = readV8("src/regexp/regexp-bytecodes.h");
const astH = readV8("src/regexp/regexp-ast.h");
const masmH = readV8("src/regexp/regexp-macro-assembler.h");

// ══ cc 侧: 名表与反汇编格式 ═══════════════════════════════════════════════
// StackCheckFlag → 名 (2)
const scsFn = cc.match(/operator<<\(std::ostream& os,\s*\n\s*RegExpMacroAssembler::StackCheckFlag val\) \{([\s\S]*?)\n\}/);
if (!scsFn) throw new Error("StackCheckFlag 名表未找到");
const scsNames = [...scsFn[1].matchAll(/StackCheckFlag::k(\w+):\s*\n\s*return os << "(\w+)";/g)].map((r) => ({ name: r[1], text: r[2] }));
if (scsNames.length !== 2) throw new Error(`StackCheckFlag 名应 2, 实数 ${scsNames.length}`);
if (scsNames[0].name !== "NoStackLimitCheck" || scsNames[0].text !== "NoCheck") throw new Error("NoCheck 名漂移");
if (scsNames[1].name !== "CheckStackLimit" || scsNames[1].text !== "Check") throw new Error("Check 名漂移");
// 交叉: masm.h 枚举 2 项
if (!masmH.includes("enum class StackCheckFlag : uint8_t {")) throw new Error("masm.h StackCheckFlag 漂移");
if (!masmH.includes("kNoStackLimitCheck = false") || !masmH.includes("kCheckStackLimit = true")) {
  throw new Error("masm.h StackCheckFlag 值漂移");
}

// StandardCharacterSet → 名 (9)
const stdFn = cc.match(/operator<<\(std::ostream& os, StandardCharacterSet val\) \{([\s\S]*?)\n\}/);
if (!stdFn) throw new Error("StandardCharacterSet 名表未找到");
const stdNames = [...stdFn[1].matchAll(/StandardCharacterSet::k(\w+):\s*\n\s*return os << "(\w+)";/g)].map((r) => ({ name: r[1], text: r[2] }));
if (stdNames.length !== 9) throw new Error(`StandardCharacterSet 名应 9, 实数 ${stdNames.length}`);
// 交叉: ast.h 枚举 9 项名集全等
const astEnum = [...astH.match(/enum class StandardCharacterSet : char \{([\s\S]*?)\};/)[1].matchAll(/k(\w+) = '/g)].map((r) => r[1]);
if (astEnum.length !== 9) throw new Error(`ast.h 标准字符集应 9, 实数 ${astEnum.length}`);
const stdSet = new Set(stdNames.map((s) => s.name));
if (astEnum.some((n) => !stdSet.has(n))) throw new Error("标准字符集名集与 ast.h 不合");

// 反汇编格式
if (!cc.includes('PrintF("[generated bytecode for regexp pattern: \'%s\']\\n", pattern);')) {
  throw new Error("反汇编头格式漂移");
}
if (!cc.includes('PrintF("%p  %4x  ", pc, offset);')) throw new Error("反汇编行前缀格式漂移");
if (!cc.includes('os << ", " << BytecodeOperands<bc>::Name(op) << ": ";')) throw new Error("操作数名格式漂移");
// 操作数值格式规则 (kBitTable 逐字节 hex2 / kChar AsUC32 / enum 名 / 其余 hex2)
if (!cc.includes("type == BytecodeOperandType::kBitTable")) throw new Error("kBitTable 分支缺失");
if (!cc.includes("AsHex(val[i], 2)")) throw new Error("位表逐字节格式漂移");
if (!cc.includes("type == BytecodeOperandType::kChar")) throw new Error("kChar 分支缺失");
if (!cc.includes("os << AsUC32(val);")) throw new Error("字符格式漂移");
if (!cc.includes("} else if constexpr (std::is_enum_v<decltype(val)>) {\n        os << val;")) {
  throw new Error("枚举直印分支漂移");
}

// ══ inl.h 侧: 61 opcode 布局金标准 ══════════════════════════════════════
// 从 bytecodes.h 重解析四表 (与 regexp-bytecodes.h.js 同法, 独立复刻)
const src = bcH.replace(/\\\r?\n\s*/g, " ");
function macroBody(name) {
  const m = src.match(new RegExp(`#define ${name}\\(V\\) (.*)`));
  if (!m) throw new Error(`regexp-bytecodes.h: ${name} 漂移`);
  return m[1].replace(/\/\*[\s\S]*?\*\//g, " ");
}
function entries(body) {
  const out = [];
  let i = 0;
  while (i < body.length) {
    const start = body.indexOf("V(", i);
    if (start < 0) break;
    let depth = 0;
    let end = start + 1;
    for (; end < body.length; end++) {
      if (body[end] === "(") depth++;
      else if (body[end] === ")") {
        depth--;
        if (depth === 0) break;
      }
    }
    out.push(body.slice(start + 2, end));
    i = end + 1;
  }
  if (out.length === 0) throw new Error("宏体零条目");
  return out;
}
function splitTopLevel(s) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of s) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}
const tupleNames = (s) => splitTopLevel(s.replace(/^\((.*)\)$/, "$1")).filter(Boolean);

// 操作数类型宽度/对齐
const CT_SIZE = { int16_t: 2, int32_t: 4, uint32_t: 4, "base::uc16": 2, uint16_t: 2, "RegExpMacroAssembler::StackCheckFlag": 1, StandardCharacterSet: 1 };
const opTypes = [];
for (const [name, ctype] of entries(macroBody("BASIC_BYTECODE_OPERAND_TYPE_LIST")).map((e) => splitTopLevel(e))) {
  opTypes.push({ name, size: CT_SIZE[ctype], align: CT_SIZE[ctype] });
}
for (const e of entries(macroBody("BASIC_BYTECODE_OPERAND_TYPE_LIMITS_LIST"))) {
  const [name, ctype, , ] = splitTopLevel(e);
  opTypes.push({ name, size: CT_SIZE[ctype], align: CT_SIZE[ctype] });
}
for (const e of entries(macroBody("SPECIAL_BYTECODE_OPERAND_TYPE_LIST"))) {
  const [name, size, align] = splitTopLevel(e);
  opTypes.push({ name, size: Number(size), align: Number(align) });
}
if (opTypes.length !== 11) throw new Error(`操作数类型应 11, 实数 ${opTypes.length}`);
const opIdx = new Map(opTypes.map((t, i) => [t.name, i]));

// opcode 四表
const bytecodes = [];
for (const sec of ["INVALID_BYTECODE_LIST", "BASIC_BYTECODE_LIST", "SPECIAL_BYTECODE_LIST", "PEEPHOLE_BYTECODE_LIST"]) {
  for (const e of entries(macroBody(sec))) {
    const [camel, , opTypesTuple] = splitTopLevel(e);
    const types = tupleNames(opTypesTuple).map((t) => {
      const m = t.match(/^ReBcOpType::k(\w+)$/);
      if (!m || !opIdx.has(m[1])) throw new Error(`${camel}: 未知类型 ${t}`);
      return m[1];
    });
    bytecodes.push({ camel, types });
  }
}
if (bytecodes.length !== 61) throw new Error(`opcode 应 61, 实数 ${bytecodes.length}`);

// inl.h 结构断言: traits 3 宏 + names + operands + 四表 + 派发
for (const anchor of [
  "DECLARE_BASIC_OPERAND_TYPE_TRAITS",
  "DECLARE_BASIC_OPERAND_TYPE_LIMITS_TRAITS",
  "DECLARE_SPECIAL_OPERAND_TYPE_TRAITS",
  "DECLARE_OPERAND_NAMES",
  "DECLARE_OPERANDS",
  "kBytecodeNames",
  "kBytecodeSizes",
  "kBytecodeFlags",
  "kOperandTypeSizes",
  "DispatchOnBytecode",
  "CalculateAlignedOffsets",
]) {
  if (!inl.includes(anchor)) throw new Error(`inl.h 缺 ${anchor}`);
}
if ((inl.match(/REGEXP_BYTECODE_LIST\(/g) || []).length !== 6) {
  throw new Error("inl.h REGEXP_BYTECODE_LIST 展开应 6 处 (names/operands/3 表/派发)");
}

// JS 独立复刻 CalculateAlignedOffsets → GOLDEN_OFFSETS/GOLDEN_SIZES
const ALIGN = 4;
const roundUp = (v, a) => Math.ceil(v / a) * a;
const goldenOffsets = bytecodes.map((bc) => {
  let offset = 1; // sizeof(Bytecode)
  const offs = [];
  for (const t of bc.types) {
    const { size, align } = opTypes[opIdx.get(t)];
    offset = roundUp(offset, align);
    if (offset % ALIGN + size > ALIGN) offset = roundUp(offset, ALIGN);
    offs.push(offset);
    offset += size;
  }
  return offs;
});
const goldenSizes = bytecodes.map((bc, i) => roundUp(goldenOffsets[i].length ? goldenOffsets[i][goldenOffsets[i].length - 1] + opTypes[opIdx.get(bc.types[bc.types.length - 1])].size : 1, ALIGN));
const totalOffsets = goldenOffsets.reduce((a, b) => a + b.length, 0);
if (goldenSizes.reduce((a, b) => a + b, 0) !== 732) throw new Error(`尺寸合计应 732, 实数 ${goldenSizes.reduce((a, b) => a + b, 0)}`);

// ══ 与 compiler 侧 bytecodes_generated.rs 双向交叉 ═══════════════════════
const gen = readFileSync(join(root, "v8-regexp-compiler", "src", "bytecodes_generated.rs"), "utf8");
const genTypes = [...gen.matchAll(/^  &\[([^\]]*)\], \/\/ (\w+)$/gm)];
if (genTypes.length !== 61) throw new Error(`compiler 侧操作数类型表应 61, 实数 ${genTypes.length}`);
for (let i = 0; i < 61; i++) {
  const a = bytecodes[i].types.join(",");
  const b = genTypes[i][1].replace(/BytecodeOperandType::/g, "").replace(/,\s*/g, ",");
  if (genTypes[i][2] !== bytecodes[i].camel || a !== b) {
    throw new Error(`交叉漂移[${i}]: ${bytecodes[i].camel} [${a}] vs compiler ${genTypes[i][2]} [${b}]`);
  }
}
const genSizes = gen.match(/GOLDEN_SIZES: \[u8; K_BYTECODE_COUNT as usize\] = \[([\s\S]*?)\];/);
if (!genSizes) throw new Error("compiler GOLDEN_SIZES 未找到");
const gs = [...genSizes[1].matchAll(/(\d+),/g)].map((r) => Number(r[1]));
if (gs.length !== 61) throw new Error("compiler GOLDEN_SIZES 应 61");
for (let i = 0; i < 61; i++) {
  if (gs[i] !== goldenSizes[i]) throw new Error(`GOLDEN_SIZES[${i}] ${bytecodes[i].camel} 漂移: ${gs[i]} vs ${goldenSizes[i]}`);
}

console.log(
  `regexp-bytecodes.cc: 名表 ${scsNames.length}+${stdNames.length}, opcode ${bytecodes.length}, ` +
    `偏移数组 61/操作数总数 ${totalOffsets}, 尺寸合计 ${goldenSizes.reduce((a, b) => a + b, 0)}, ` +
    `compiler 交叉 61/61 ✓`,
);

// ══ 生成 Rust ═════════════════════════════════════════════════════════════
const body = `${banner(
  "src/regexp/regexp-bytecodes.cc.js",
  "src/regexp/regexp-bytecodes.{cc,-inl.h}",
  "反汇编名表/格式 + 61 opcode 布局金标准 (GOLDEN_OFFSETS); 同源性: v8-regexp-compiler/src/bytecodes_generated.rs (脚本交叉)",
)}
/// StackCheckFlag → 反汇编名 (cc:19-28)
pub const STACK_CHECK_FLAG_NAMES: [(&str, &str); ${scsNames.length}] = [
${scsNames.map((s) => `  ("${s.name}", "${s.text}"),`).join("\n")}
];

/// StandardCharacterSet → 反汇编名 (cc:30-52; 与 syntax 侧字符表 9 项同源)
pub const STANDARD_CHARACTER_SET_NAMES: [(&str, &str); ${stdNames.length}] = [
${stdNames.map((s) => `  ("${s.name}", "${s.text}"),`).join("\n")}
];

// ── 反汇编格式 (cc:56-98) ──
/// 头: [generated bytecode for regexp pattern: '<pattern>']
pub const K_DISASSEMBLE_HEADER: &str = "[generated bytecode for regexp pattern: '%s']";
/// 行前缀: <指针>  <4 位十六进制偏移>  (双空格分隔)
pub const K_DISASSEMBLE_ROW_PREFIX: &str = "%p  %4x  ";
/// 操作数: ", <名>: <值>"
pub const K_DISASSEMBLE_OPERAND_FMT: &str = ", ";
/// 位表操作数: 逐字节 2 位十六进制
pub const K_DISASSEMBLE_BITTABLE_HEX_WIDTH: usize = 2;

// ── 61 opcode 布局金标准 (JS 复刻 inl.h:107-136 CalculateAlignedOffsets) ──
/// 逐条操作数偏移 (首操作数从 1 = sizeof(Bytecode) 起; 4 字节块对齐)
pub(crate) const GOLDEN_OFFSETS: [&[u32]; 61] = [
${bytecodes.map((b, i) => `  &[${goldenOffsets[i].join(", ")}], // ${b.camel}`).join("\n")}
];

/// 逐条总尺寸 (零操作数 = 4; 末操作数尾 + RoundUp 4)
pub(crate) const GOLDEN_SIZES: [u8; 61] = [
${bytecodes.map((b, i) => `  ${goldenSizes[i]}, // ${b.camel}`).join("\n")}
];

pub const K_BYTECODE_COUNT: u8 = 61;
/// 4 字节块对齐 (kBytecodeAlignment)
pub const K_BYTECODE_ALIGNMENT: u32 = 4;
/// 首偏移 = 操作码本身 1 字节
pub const K_FIRST_OFFSET: u32 = 1;

const _: () = assert!(GOLDEN_OFFSETS.len() == 61 && GOLDEN_SIZES.len() == 61);
const _: () = assert!(GOLDEN_SIZES.iter().sum::<u8>() as u32 == 732);
const _: () = assert!(GOLDEN_OFFSETS[0].is_empty()); // Break 零操作数
const _: () = assert!(STACK_CHECK_FLAG_NAMES.len() == 2 && STANDARD_CHARACTER_SET_NAMES.len() == 9);
`;

writeSrc("v8-regexp-exec", "bytecodes_cc_generated.rs", body);
console.log("written: v8-regexp-exec/src/bytecodes_cc_generated.rs");
